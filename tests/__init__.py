# Modular RAG MCP Server 的测试包

"""
标准的三层测试体系（Unit / Integration / E2E），外加一个存放公共测试数据的 fixtures。它们各自负责不同粒度的验证，分工很明确。

📁 unit（单元测试）
这是数量最多、跑得最快的一层。它的目标是隔离外部依赖（比如用 Mock 把大模型 API、真实数据库都替换掉），专门验证单个函数或类的内部逻辑对不对。比如验证文本切分器有没有切错、工厂类路由逻辑正不正确。

📁 integration（集成测试）
这一层用来验证多个模块拼在一起协作时，数据能不能正确流转。它通常会用到真实的本地资源（比如临时的 ChromaDB），但会 Mock 掉昂贵的外部 API。比如测试从“加载 → 切分 → 转换 → 存储”的完整摄取流水线，或者验证稠密检索和稀疏检索融合后的结果排序。

📁 e2e（端到端测试）
这是最接近真实用户场景的一层，数量少但最全面。它使用极少的 Mock，跑通完整的业务流程。比如用真实的流水线跑一遍数据摄取，然后检查检索命中率（hit_rate）是否达标；或者用 Streamlit 的测试框架把 Dashboard 页面渲染一遍，确保不报错。

📁 fixtures（测试夹具/固定数据）
这里通常不包含测试逻辑，而是存放测试用的公共数据或预置环境。比如专门用来做回归测试的“黄金测试集”（Golden Test Set，包含已知的查询和标准答案），或者一些供测试用的示例 PDF 文件。

可以用 pytest 配合标记来分层执行，比如 pytest -m unit 只跑最快的单元测试。
"""
